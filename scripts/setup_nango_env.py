"""
Create deploy/nango/.env with freshly generated secrets for the self-hosted Nango stack.

    uv run python scripts/setup_nango_env.py

Never overwrites an existing file: the encryption key protects every stored OAuth token, so
regenerating it would make existing connections unreadable.
"""
from __future__ import annotations

import base64
import secrets
import sys
from pathlib import Path

TARGET = Path(__file__).resolve().parents[1] / "deploy" / "nango" / ".env"


def main() -> None:
    if TARGET.exists():
        print(f"{TARGET} already exists -- leaving it alone.")
        print("(Its NANGO_ENCRYPTION_KEY protects stored tokens; do not replace it on a stack that has connections.)")
        return
    TARGET.write_text(
        "\n".join(
            [
                "# Generated by scripts/setup_nango_env.py -- keep this file private, it is git-ignored.",
                f"NANGO_ENCRYPTION_KEY={base64.b64encode(secrets.token_bytes(32)).decode()}",
                f"NANGO_DB_PASSWORD={secrets.token_urlsafe(24)}",
                "NANGO_SERVER_URL=http://localhost:3003",
                "NANGO_CONNECT_URL=http://localhost:3009",
                "",
            ]
        ),
        encoding="utf-8",
    )
    print(f"Wrote {TARGET}")
    print("Next: start Nango and create your dashboard account -- see docs/NANGO_SETUP.md")


if __name__ == "__main__":
    sys.exit(main())
